# 反向
REVERSE_ADDR_LIST = [0] * 16
for i in range(16):
    REVERSE_ADDR_LIST[ADDR_LIST[i]] = i

def reverse_14000149C(b):
    high = REVERSE_ADDR_LIST[(b >> 4) & 0x0F]
    low = REVERSE_ADDR_LIST[b & 0x0F]
    return (high << 4) | low

def reverse_1400014B2(b):
    # 先循环左移3位，再循环右移4位
    b = ((b << 3) & 0xF8) | ((b >> 5) & 0x07)
    b = ((b >> 4) & 0x0F) | ((b << 4) & 0xF0)
    return b

def reverse_byte(b):
    return reverse_1400014B2(reverse_14000149C(b))

